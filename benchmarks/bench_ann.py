#!/usr/bin/env python3
"""Benchmark suite: FlatIndex (exact) vs HNSWIndex (approximate).

Measures recall@k and query-latency percentiles for both indexes across a
range of dataset sizes, using FlatIndex's exact results as the recall
ground truth. Run directly:

    python benchmarks/bench_ann.py
    python benchmarks/bench_ann.py --sizes 1000 10000 100000 --plot

Writes a Markdown report to docs/BENCHMARKS.md (and, with --plot, a PNG
chart alongside it) so the numbers can be published rather than just
printed to a terminal that scrolls away.
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from nexusdb.core.index.flat_index import FlatIndex  # noqa: E402
from nexusdb.core.index.hnsw_index import HNSWIndex  # noqa: E402
from nexusdb.core.vector import Vector  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = REPO_ROOT / "docs"


@dataclass
class BenchmarkRow:
    n: int
    dimension: int
    metric: str
    m: int
    ef_construction: int
    ef_search: int
    flat_build_s: float
    hnsw_build_s: float
    recall_at_k: float
    flat_p50_ms: float
    flat_p95_ms: float
    hnsw_p50_ms: float
    hnsw_p95_ms: float
    speedup_p50: float
    speedup_p95: float
    hnsw_avg_distance_computations: float


def _make_vectors(n: int, dim: int, seed: int) -> list[Vector]:
    rng = np.random.default_rng(seed)
    embeddings = rng.standard_normal((n, dim)).astype(np.float32)
    return [Vector(embedding=embeddings[i], id=f"vec-{i}") for i in range(n)]


def _percentiles_ms(latencies_s: list[float]) -> tuple[float, float]:
    p50 = statistics.median(latencies_s) * 1000
    p95 = float(np.percentile(latencies_s, 95)) * 1000
    return p50, p95


def run_one(
    n: int,
    dim: int,
    k: int,
    m: int,
    ef_construction: int,
    ef_search: int,
    num_queries: int,
    metric: str,
    seed: int,
) -> BenchmarkRow:
    vectors = _make_vectors(n, dim, seed=seed)
    rng = np.random.default_rng(seed + 1)
    queries = rng.standard_normal((num_queries, dim)).astype(np.float32)

    flat = FlatIndex(dimension=dim, metric=metric)
    t0 = time.perf_counter()
    flat.add(vectors)
    flat_build_s = time.perf_counter() - t0

    hnsw = HNSWIndex(
        dimension=dim,
        metric=metric,
        m=m,
        ef_construction=ef_construction,
        ef_search=ef_search,
        seed=seed,
    )
    t0 = time.perf_counter()
    hnsw.add(vectors)
    hnsw_build_s = time.perf_counter() - t0

    recalls = []
    flat_latencies = []
    hnsw_latencies = []
    hnsw_distance_counts = []
    for query in queries:
        t0 = time.perf_counter()
        flat_results = flat.search(query, k=k)
        flat_latencies.append(time.perf_counter() - t0)

        t0 = time.perf_counter()
        hnsw_results = hnsw.search(query, k=k)
        hnsw_latencies.append(time.perf_counter() - t0)
        hnsw_distance_counts.append(hnsw.last_search_distance_count)

        exact_ids = {r.id for r in flat_results}
        approx_ids = {r.id for r in hnsw_results}
        recalls.append(len(exact_ids & approx_ids) / k)

    flat_p50, flat_p95 = _percentiles_ms(flat_latencies)
    hnsw_p50, hnsw_p95 = _percentiles_ms(hnsw_latencies)

    return BenchmarkRow(
        n=n,
        dimension=dim,
        metric=metric,
        m=m,
        ef_construction=ef_construction,
        ef_search=ef_search,
        flat_build_s=flat_build_s,
        hnsw_build_s=hnsw_build_s,
        recall_at_k=float(np.mean(recalls)),
        flat_p50_ms=flat_p50,
        flat_p95_ms=flat_p95,
        hnsw_p50_ms=hnsw_p50,
        hnsw_p95_ms=hnsw_p95,
        speedup_p50=flat_p50 / hnsw_p50 if hnsw_p50 > 0 else float("inf"),
        speedup_p95=flat_p95 / hnsw_p95 if hnsw_p95 > 0 else float("inf"),
        hnsw_avg_distance_computations=float(np.mean(hnsw_distance_counts)),
    )


def render_markdown(rows: list[BenchmarkRow], k: int) -> str:
    lines = [
        "# ANN Benchmarks: FlatIndex vs HNSWIndex",
        "",
        f"Generated by `benchmarks/bench_ann.py` on {platform.platform()}, "
        f"Python {platform.python_version()}, NumPy {np.__version__}.",
        "",
        "Synthetic Gaussian-random vectors, cosine metric, "
        f"k={k}, recall@{k} measured against `FlatIndex`'s exact results as ground truth.",
        "",
        "| n | dim | m | ef_construction | ef_search | recall@"
        f"{k} | flat build (s) | hnsw build (s) | flat p50 (ms) | hnsw p50 (ms) | "
        "flat p95 (ms) | hnsw p95 (ms) | p50 speedup | p95 speedup | "
        "flat dist. computed | hnsw dist. computed (avg) |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r.n:,} | {r.dimension} | {r.m} | {r.ef_construction} | {r.ef_search} | "
            f"{r.recall_at_k:.3f} | {r.flat_build_s:.3f} | {r.hnsw_build_s:.3f} | "
            f"{r.flat_p50_ms:.3f} | {r.hnsw_p50_ms:.3f} | "
            f"{r.flat_p95_ms:.3f} | {r.hnsw_p95_ms:.3f} | "
            f"{r.speedup_p50:.2f}x | {r.speedup_p95:.2f}x | "
            f"{r.n:,} | {r.hnsw_avg_distance_computations:,.0f} |"
        )

    lines += [
        "",
        "## Reading these numbers",
        "",
        "- **recall@k** is `FlatIndex`'s exact top-k intersected with `HNSWIndex`'s "
        "approximate top-k, averaged over the query set — 1.0 means HNSW returned "
        "exactly the same k neighbors as brute force.",
        "- **speedup** is `flat latency / hnsw latency`; >1x means HNSW answered "
        "faster than exhaustive search at that dataset size.",
        "- **dist. computed** is how many vector-to-vector distance evaluations "
        "each query actually performs — `FlatIndex` always computes exactly n "
        "(it checks every vector); `HNSWIndex`'s count grows much more slowly "
        "as n grows, which is the algorithmic complexity win (O(log n) vs O(n)) "
        "made concrete, independent of wall-clock.",
        "- `FlatIndex` computes distances with one vectorized NumPy call over the "
        "whole matrix — extremely fast per query even at six figures of vectors. "
        "`HNSWIndex` is a pure-Python graph walk: each hop is its own small NumPy "
        "call plus Python-level heap bookkeeping. That constant-factor interpreter "
        "overhead is real, and it means the crossover point where HNSW's O(log n) "
        "traversal wins in *wall-clock* terms — not just in distance computations "
        "performed — sits at a larger n than a compiled implementation (e.g. "
        "hnswlib/FAISS) would need. Where the numbers above don't yet show HNSW "
        "ahead, that gap is exactly why real vector databases implement the hot "
        "loop in C/C++/Rust rather than pure Python.",
        "- **Tradeoff, explicitly**: `FlatIndex` is exact (recall is always 1.0) "
        "and its cost grows linearly with n. `HNSWIndex` is approximate and tunable "
        "— `ef_search` trades recall for latency at query time, `m`/`ef_construction` "
        "trade build time and memory for graph quality — and its distance-computation "
        "cost grows roughly logarithmically with n, which is what eventually wins at scale.",
        "",
    ]
    return "\n".join(lines)


def render_plot(rows: list[BenchmarkRow], out_path: Path, k: int) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    ns = [r.n for r in rows]
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4.5))

    ax1.plot(ns, [r.flat_p50_ms for r in rows], "o-", label="FlatIndex (exact)")
    ax1.plot(ns, [r.hnsw_p50_ms for r in rows], "o-", label="HNSWIndex (approx)")
    ax1.set_xscale("log")
    ax1.set_yscale("log")
    ax1.set_xlabel("dataset size (n)")
    ax1.set_ylabel("p50 query latency (ms)")
    ax1.set_title("Query latency vs dataset size")
    ax1.legend()
    ax1.grid(True, which="both", alpha=0.3)

    ax2.plot(ns, [r.recall_at_k for r in rows], "o-", color="green")
    ax2.set_xscale("log")
    ax2.set_xlabel("dataset size (n)")
    ax2.set_ylabel(f"recall@{k}")
    ax2.set_ylim(0, 1.05)
    ax2.set_title("HNSW recall vs dataset size")
    ax2.grid(True, which="both", alpha=0.3)

    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sizes", type=int, nargs="+", default=[1_000, 10_000, 100_000])
    parser.add_argument("--dim", type=int, default=128)
    parser.add_argument("--k", type=int, default=10)
    parser.add_argument("--m", type=int, default=16)
    parser.add_argument("--ef-construction", type=int, default=100)
    parser.add_argument("--ef-search", type=int, default=50)
    parser.add_argument("--num-queries", type=int, default=50)
    parser.add_argument("--metric", type=str, default="cosine")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--plot", action="store_true", help="Also render a PNG chart")
    parser.add_argument(
        "--json-out", type=str, default=None, help="Optional path to dump raw results as JSON"
    )
    args = parser.parse_args()

    rows: list[BenchmarkRow] = []
    for n in args.sizes:
        print(f"[bench] n={n} dim={args.dim} m={args.m} ef_construction={args.ef_construction} ...")
        t0 = time.perf_counter()
        row = run_one(
            n=n,
            dim=args.dim,
            k=args.k,
            m=args.m,
            ef_construction=args.ef_construction,
            ef_search=args.ef_search,
            num_queries=args.num_queries,
            metric=args.metric,
            seed=args.seed,
        )
        rows.append(row)
        print(
            f"[bench] n={n}: recall@{args.k}={row.recall_at_k:.3f} "
            f"flat_p50={row.flat_p50_ms:.3f}ms hnsw_p50={row.hnsw_p50_ms:.3f}ms "
            f"(speedup {row.speedup_p50:.2f}x) build={row.hnsw_build_s:.1f}s "
            f"[{time.perf_counter() - t0:.1f}s total]"
        )

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    report = render_markdown(rows, k=args.k)
    (DOCS_DIR / "BENCHMARKS.md").write_text(report)
    print(f"[bench] wrote {DOCS_DIR / 'BENCHMARKS.md'}")

    if args.plot:
        try:
            render_plot(rows, DOCS_DIR / "benchmark_plot.png", k=args.k)
            print(f"[bench] wrote {DOCS_DIR / 'benchmark_plot.png'}")
        except ImportError:
            print("[bench] matplotlib not installed — skipping plot (pip install '.[benchmark]')")

    if args.json_out:
        Path(args.json_out).write_text(json.dumps([asdict(r) for r in rows], indent=2))
        print(f"[bench] wrote {args.json_out}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
